fn readme(d: &GameLogicData) -> String {
    let mut o = page(
        "Reference tables",
        &format!(
            "Generated from the built-in rules data (`data/rules/`), version {GAME_LOGIC_DATA_VERSION}, which \
             {} use. Do not edit these files: change the data or \
             `examples/gen_docs.rs` and regenerate. The test `tests/docs_fresh.rs` fails when they drift.",
            game_versions(GAME_LOGIC_DATA_VERSION)
        ),
    );
    o.push_str("| Document | Contents |\n| --- | --- |\n");
    o.push_str(&format!(
        "| [units.md](units.md) | {} units: stats, cost, abilities, unlocking tech |\n",
        d.units.len()
    ));
    o.push_str(&format!(
        "| [improvements.md](improvements.md) | {} improvements and buildings: cost, rewards, placement |\n",
        d.improvements.len()
    ));
    o.push_str(&format!("| [techs.md](techs.md) | {} techs: tree, price, what each unlocks |\n", d.tech.len()));
    o.push_str(&format!(
        "| [tribes.md](tribes.md) | {} tribes: start tech and unit, terrain and resource weights, overrides |\n",
        playable_tribes(d).len()
    ));
    o.push_str(&format!(
        "| [terrain-and-resources.md](terrain-and-resources.md) | {} terrains, {} resources, movement and defence unlocks |\n",
        d.terrains.len(),
        d.resources.len()
    ));
    o.push_str("| [abilities.md](abilities.md) | Every ability name and who has it |\n");
    o.push_str("| [tasks-and-diplomacy.md](tasks-and-diplomacy.md) | Tasks and monuments, embassy numbers, skins |\n");
    o.push_str("| [changelog.md](changelog.md) | What each older rules version changed |\n");
    o.push_str("\nHow the numbers are used is in the mechanic documents, start at [../README.md](../README.md).\n");
    o
}

