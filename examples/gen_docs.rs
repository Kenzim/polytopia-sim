fn sections(d: &GameLogicData) -> Vec<(&'static str, Records)> {
    let mut diplomacy = Records::new();
    if let Some(x) = &d.diplomacy {
        diplomacy.insert(
            "diplomacy".to_string(),
            vec![
                ("embassy_cost", x.embassy_cost.to_string()),
                ("embassy_income", x.embassy_income.to_string()),
                ("embasy_growth_time", x.embasy_growth_time.to_string()),
                ("embassy_max_level", x.embassy_max_level.to_string()),
                ("embassy_upgrade_cost", x.embassy_upgrade_cost.to_string()),
                ("dividend_income", x.dividend_income.to_string()),
                ("embassy_tech_price_multiplier", x.embassy_tech_price_multiplier.to_string()),
            ],
        );
    }
    vec![
        ("unit", d.units.iter().map(|(k, v)| (k.clone(), unit_fields(v))).collect()),
        ("tribe", d.tribes.iter().map(|(k, v)| (k.clone(), tribe_fields(v))).collect()),
        ("tech", d.tech.iter().map(|(k, v)| (k.clone(), tech_fields(v))).collect()),
        ("improvement", d.improvements.iter().map(|(k, v)| (k.clone(), improvement_fields(v))).collect()),
        ("terrain", d.terrains.iter().map(|(k, v)| (k.clone(), vec![("idx", v.idx.to_string())])).collect()),
        (
            "resource",
            d.resources
                .iter()
                .map(|(k, v)| {
                    (
                        k.clone(),
                        vec![
                            ("idx", v.idx.to_string()),
                            ("resource_terrain_requirements", list_text(&v.resource_terrain_requirements)),
                        ],
                    )
                })
                .collect(),
        ),
        (
            "task",
            d.tasks
                .iter()
                .map(|(k, v)| {
                    (
                        k.clone(),
                        vec![("idx", v.idx.to_string()), ("improvement_unlocks", list_text(&v.improvement_unlocks))],
                    )
                })
                .collect(),
        ),
        (
            "skin",
            d.skins
                .iter()
                .map(|(k, v)| {
                    (
                        k.clone(),
                        vec![
                            ("color", v.color.map(|c| c.to_string()).unwrap_or_default()),
                            ("language", v.language.clone()),
                        ],
                    )
                })
                .collect(),
        ),
        ("diplomacy", diplomacy),
    ]
}

fn shown(s: &str) -> String {
    if s.is_empty() {
        "none".to_string()
    } else {
        code(s)
    }
}

/// The differences of `older` against `newer`, as bullet lines (empty when the rules are identical).
fn diff_lines(older: &GameLogicData, newer: &GameLogicData, old_v: i32, new_v: i32) -> Vec<String> {
    let mut lines = Vec::new();
    let (a, b) = (sections(older), sections(newer));
    for ((kind, old), (_, new)) in a.iter().zip(b.iter()) {
        let mut ids: Vec<&String> = old.keys().chain(new.keys()).collect();
        ids.sort();
        ids.dedup();
        for id in ids {
            match (old.get(id), new.get(id)) {
                (Some(_), None) => lines.push(format!("- {kind} `{id}`: only in v{old_v} (absent in v{new_v})")),
                (None, Some(_)) => lines.push(format!("- {kind} `{id}`: absent in v{old_v} (added in v{new_v})")),
                (Some(x), Some(y)) => {
                    for ((name, ov), (_, nv)) in x.iter().zip(y.iter()) {
                        if ov != nv {
                            lines.push(format!(
                                "- {kind} `{id}`, `{name}`: {} in v{old_v} (v{new_v}: {})",
                                shown(ov),
                                shown(nv)
                            ));
                        }
                    }
                }
                (None, None) => {}
            }
        }
    }
    lines
}

/// Game versions that use a rules version, as ranges, e.g. `51 to 59`.
fn game_versions(rules_version: i32) -> String {
    let games: Vec<i32> =
        (MIN_SUPPORTED_GAME_VERSION..=GAME_VERSION).filter(|g| logic_data_version(*g) == rules_version).collect();
    match (games.first(), games.last()) {
        (Some(a), Some(b)) if a == b => format!("game version {a}"),
        (Some(a), Some(b)) => format!("game versions {a} to {b}"),
        _ => "no supported game version".to_string(),
    }
}

fn changelog() -> String {
    let mut o = page(
        "Rules version change log",
        &format!(
            "The engine keeps rules versions {OLDEST_VERSION} to {GAME_LOGIC_DATA_VERSION}. Version \
             {GAME_LOGIC_DATA_VERSION} is stored in full (`data/rules/v28.json`); every older version is a change \
             file against the next newer one (`v27.json` against 28, and so on). Each section below lists what \
             that older version differs in, read from the loaded rules: the value in the older version first, the \
             next version's value in brackets. A game version picks its rules version with \
             `logic_data_version` (see [versions](../versions.md)). Values are shown as stored: health, attack \
             and defence in tenths."
        ),
    );
    let mut newer = load(GAME_LOGIC_DATA_VERSION);
    o.push_str(&format!(
        "## Rules v{GAME_LOGIC_DATA_VERSION}\n\nThe current rules ({}). See the other reference documents for their content.\n\n",
        game_versions(GAME_LOGIC_DATA_VERSION)
    ));
    for v in (OLDEST_VERSION..GAME_LOGIC_DATA_VERSION).rev() {
        let older = load(v);
        let lines = diff_lines(&older, &newer, v, v + 1);
        o.push_str(&format!("## Rules v{v}\n\n{}, differing from v{}.\n\n", game_versions(v), v + 1));
        if lines.is_empty() {
            o.push_str("No differences.\n\n");
        } else {
            o.push_str(&lines.join("\n"));
            o.push_str("\n\n");
        }
        newer = older;
    }
    o
}
