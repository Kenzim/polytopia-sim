fn terrain_and_resources(d: &GameLogicData) -> String {
    let mut o = page(
        "Terrain and resources",
        "The terrains and resources of the current rules, what can be built on them, and which techs open \
         them up. The map is generated by [map generation](../map-generation.md); movement is in \
         [movement](../movement.md).",
    );
    o.push_str("## Terrain\n\n");
    let mut t = Table::new(&[
        "Terrain",
        "idx",
        "Resources that can spawn",
        "Improvements built on it",
        "Entered once known",
        "Defence bonus tech",
    ]);
    let mut list: Vec<_> = d.terrains.values().collect();
    list.sort_by_key(|x| x.idx);
    for x in list {
        let res: Vec<String> = {
            let mut r: Vec<_> =
                d.resources.values().filter(|r| r.resource_terrain_requirements.contains(&x.id)).collect();
            r.sort_by_key(|r| r.idx);
            r.into_iter().map(|r| r.id.clone()).collect()
        };
        let imps: Vec<String> = {
            let mut v: Vec<_> = d
                .improvements
                .values()
                .filter(|i| i.terrain_requirements.iter().any(|r| r.terrain.as_deref() == Some(x.id.as_str())))
                .collect();
            v.sort_by_key(|i| i.idx);
            v.into_iter().map(|i| i.id.clone()).collect()
        };
        let mv: Vec<String> = techs_by_idx(d)
            .into_iter()
            .filter(|t| t.movement_unlocks.contains_key(&x.id))
            .map(|t| t.id.clone())
            .collect();
        let def: Vec<String> = techs_by_idx(d)
            .into_iter()
            .filter_map(|t| t.defence_bonus_unlocks.get(&x.id).map(|v| format!("{} ({v})", t.id)))
            .collect();
        t.row(vec![code(&x.id), x.idx.to_string(), codes(&res), codes(&imps), codes(&mv), codes(&def)]);
    }
    o.push_str(&t.render());
    o.push_str(
        "\n*Entered once known*: the techs that let a player's land units enter the terrain (the rules also \
         store a number per entry, which the engine does not read). *Defence bonus tech*: the tech that gives \
         units standing on the terrain the 1.5 times defence bonus; the number is the stored value.\n\n",
    );

    o.push_str("## Resources\n\n");
    let mut t = Table::new(&["Resource", "idx", "Spawns on", "Improvement that harvests it"]);
    let mut list: Vec<_> = d.resources.values().collect();
    list.sort_by_key(|x| x.idx);
    for x in list {
        let imps: Vec<String> = {
            let mut v: Vec<_> = d
                .improvements
                .values()
                .filter(|i| i.terrain_requirements.iter().any(|r| r.resource.as_deref() == Some(x.id.as_str())))
                .collect();
            v.sort_by_key(|i| i.idx);
            v.into_iter().map(|i| i.id.clone()).collect()
        };
        t.row(vec![code(&x.id), x.idx.to_string(), codes(&x.resource_terrain_requirements), codes(&imps)]);
    }
    o.push_str(&t.render());
    o
}

