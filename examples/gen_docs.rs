//! Generates the reference documents in `docs/reference/` from the built-in rules data.
//!
//! ```text
//! cargo run --release --example gen_docs            # rewrite docs/reference
//! cargo run --release --example gen_docs -- --check # exit 1 if a committed file differs
//! cargo run --release --example gen_docs -- <dir>   # write somewhere else
//! ```
//!
//! Everything comes from `polytopia_sim::data::load_game_logic_data` (the files in `data/rules/`), plus the
//! engine's own tech price and ability tables, so a generated number cannot disagree with the engine. The
//! test `tests/docs_fresh.rs` includes this file and fails when the committed documents differ from
//! [`generate`].

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use polytopia_sim::data::rules::OLDEST_VERSION;
use polytopia_sim::data::{
    load_game_logic_data, weapon_name, GameLogicData, ImprovementData, TechData, TribeData, UnitData,
    GAME_LOGIC_DATA_VERSION,
};
use polytopia_sim::engine::tables::{improvement_ability_id, player_ability_id};
use polytopia_sim::rules::economy::tech_price;
use polytopia_sim::{logic_data_version, GAME_VERSION, MIN_SUPPORTED_GAME_VERSION};

/// Rows of the tribe table that are not playable tribes.
const INTERNAL: [&str; 2] = ["none", "nature"];

const BANNER: &str = "<!-- Generated by examples/gen_docs.rs from data/rules. Do not edit by hand: \
run `cargo run --release --example gen_docs` and commit the result. -->";

/// Every generated document: (file name inside `docs/reference/`, text).
pub fn generate() -> Vec<(String, String)> {
    let current = load(GAME_LOGIC_DATA_VERSION);
    vec![
        ("README.md".to_string(), readme(&current)),
        ("units.md".to_string(), units(&current)),
        ("improvements.md".to_string(), improvements(&current)),
        ("techs.md".to_string(), techs(&current)),
        ("tribes.md".to_string(), tribes(&current)),
        ("terrain-and-resources.md".to_string(), terrain_and_resources(&current)),
        ("abilities.md".to_string(), abilities(&current)),
        ("tasks-and-diplomacy.md".to_string(), tasks_and_diplomacy(&current)),
        ("changelog.md".to_string(), changelog()),
    ]
}

/// The directory the committed documents live in.
pub fn reference_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("docs").join("reference")
}

#[allow(dead_code)]
fn main() {
    let mut check = false;
    let mut out = reference_dir();
    for arg in std::env::args().skip(1) {
        if arg == "--check" {
            check = true;
        } else {
            out = PathBuf::from(arg);
        }
    }
    let files = generate();
    if check {
        let mut stale = 0;
        for (name, text) in &files {
            if std::fs::read_to_string(out.join(name)).ok().as_deref() != Some(text.as_str()) {
                eprintln!("differs: {}", out.join(name).display());
                stale += 1;
            }
        }
        if stale > 0 {
            std::process::exit(1);
        }
        println!("{} files up to date", files.len());
        return;
    }
    std::fs::create_dir_all(&out).expect("create output directory");
    for (name, text) in &files {
        std::fs::write(out.join(name), text).expect("write document");
    }
    println!("wrote {} files to {}", files.len(), out.display());
}

fn load(version: i32) -> GameLogicData {
    load_game_logic_data(version).unwrap_or_else(|err| panic!("rules v{version}: {err}"))
}

