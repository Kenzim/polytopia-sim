// Markdown helpers

struct Table {
    head: Vec<&'static str>,
    rows: Vec<Vec<String>>,
}

impl Table {
    fn new(head: &[&'static str]) -> Self {
        Self { head: head.to_vec(), rows: Vec::new() }
    }

    fn row(&mut self, cells: Vec<String>) {
        assert_eq!(cells.len(), self.head.len(), "table row width");
        self.rows.push(cells);
    }

    fn render(&self) -> String {
        let cell = |s: &str| s.replace('|', "\\|").replace('\n', " ");
        let mut out = String::new();
        out.push_str(&format!("| {} |\n", self.head.join(" | ")));
        out.push_str(&format!("|{}\n", " --- |".repeat(self.head.len())));
        for row in &self.rows {
            let cells: Vec<String> = row.iter().map(|c| cell(c)).collect();
            out.push_str(&format!("| {} |\n", cells.join(" | ")));
        }
        out
    }
}

fn code(s: &str) -> String {
    format!("`{s}`")
}

fn codes(items: &[String]) -> String {
    if items.is_empty() {
        "-".to_string()
    } else {
        items.iter().map(|s| code(s)).collect::<Vec<_>>().join(", ")
    }
}

fn opt(v: Option<i32>) -> String {
    v.map_or("-".to_string(), |n| n.to_string())
}

/// A value stored in tenths (health, attack, defence), as the game displays it.
fn tenths(v: i32) -> String {
    if v % 10 == 0 {
        (v / 10).to_string()
    } else {
        format!("{}.{}", v / 10, (v % 10).abs())
    }
}

fn page(title: &str, intro: &str) -> String {
    format!("{BANNER}\n\n# {title}\n\n{intro}\n\n")
}

fn tribe_label(id: &str) -> String {
    code(id)
}

/// Playable tribes (not the `none` and `nature` rows), by idx.
fn playable_tribes(d: &GameLogicData) -> Vec<&TribeData> {
    let mut v: Vec<&TribeData> = d.tribes.values().filter(|t| !INTERNAL.contains(&t.id.as_str())).collect();
    v.sort_by_key(|t| t.idx);
    v
}

fn techs_by_idx(d: &GameLogicData) -> Vec<&TechData> {
    let mut v: Vec<&TechData> = d.tech.values().collect();
    v.sort_by_key(|t| t.idx);
    v
}

/// Techs (by idx) whose list selected by `pick` contains `id`.
fn unlocked_by(d: &GameLogicData, id: &str, pick: fn(&TechData) -> &Vec<String>) -> Vec<String> {
    techs_by_idx(d).into_iter().filter(|t| pick(t).iter().any(|u| u == id)).map(|t| t.id.clone()).collect()
}

fn map_list<V: std::fmt::Display>(m: &BTreeMap<String, V>) -> String {
    m.iter().map(|(k, v)| format!("{k}={v}")).collect::<Vec<_>>().join(", ")
}

