fn abilities(d: &GameLogicData) -> String {
    let mut o = page(
        "Abilities",
        "Every ability name in the current rules and who has it. The *engine id* is the number the engine \
         uses internally; `-` means the engine does not know the name. What each ability does is in \
         [../abilities.md](../abilities.md).",
    );
    let section = |title: &str, owners: BTreeMap<String, Vec<String>>, id: &dyn Fn(&str) -> Option<i32>| {
        let mut s = format!("## {title}\n\n");
        let mut t = Table::new(&["Ability", "Engine id", "Held by"]);
        let mut rows: Vec<(Option<i32>, String, Vec<String>)> =
            owners.into_iter().map(|(k, v)| (id(&k), k, v)).collect();
        rows.sort_by(|a, b| (a.0.is_none(), a.0, &a.1).cmp(&(b.0.is_none(), b.0, &b.1)));
        for (n, name, who) in rows {
            t.row(vec![code(&name), n.map_or("-".to_string(), |n| n.to_string()), who.join(", ")]);
        }
        s.push_str(&t.render());
        s.push('\n');
        s
    };

    let mut u: BTreeMap<String, Vec<String>> = BTreeMap::new();
    let mut units: Vec<&UnitData> = d.units.values().collect();
    units.sort_by_key(|x| x.idx);
    for x in units {
        for a in &x.unit_abilities {
            u.entry(a.clone()).or_default().push(code(&x.id));
        }
    }
    o.push_str(&section("Unit abilities", u, &|n| polytopia_sim::ai::decide::unit_ability_id(n)));

    let mut i: BTreeMap<String, Vec<String>> = BTreeMap::new();
    let mut imps: Vec<&ImprovementData> = d.improvements.values().collect();
    imps.sort_by_key(|x| x.idx);
    for x in imps {
        for a in &x.improvement_abilities {
            i.entry(a.clone()).or_default().push(code(&x.id));
        }
    }
    o.push_str(&section("Improvement abilities", i, &|n| improvement_ability_id(n)));

    let mut p: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for x in techs_by_idx(d) {
        for a in &x.ability_unlocks {
            p.entry(a.clone()).or_default().push(format!("tech {}", code(&x.id)));
        }
    }
    o.push_str(&section("Player abilities (unlocked by techs)", p, &|n| player_ability_id(n)));

    let mut tr: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for x in playable_tribes(d) {
        for a in &x.tribe_abilities {
            tr.entry(a.clone()).or_default().push(tribe_label(&x.id));
        }
    }
    let mut s = String::from("## Tribe abilities\n\n");
    let mut t = Table::new(&["Ability", "Held by"]);
    for (k, v) in tr {
        t.row(vec![code(&k), v.join(", ")]);
    }
    s.push_str(&t.render());
    o.push_str(&s);
    o
}

