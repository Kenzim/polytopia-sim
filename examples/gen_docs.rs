fn unit_tribes(d: &GameLogicData) -> BTreeMap<String, Vec<String>> {
    let mut m: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for t in playable_tribes(d) {
        for (base, unit) in &t.unit_overrides {
            m.entry(unit.clone()).or_default().push(format!("{} ({base})", tribe_label(&t.id)));
        }
    }
    m
}

fn units(d: &GameLogicData) -> String {
    let mut o = page(
        "Units",
        "Every unit type in the current rules. Health, attack and defence are shown as the game shows them: the \
         data stores tenths (a warrior has health 100, shown as 10). *XP* is the experience a unit needs before \
         it can be promoted (0 means it cannot be promoted). *Hidden* units are not offered in the train menu: \
         they are starting units, spawns, upgrades and Nature's units. *Tribe* lists the tribes that use the \
         unit in place of a standard one (the standard unit is in brackets).",
    );
    let owners = unit_tribes(d);
    let mut list: Vec<&UnitData> = d.units.values().collect();
    list.sort_by_key(|u| u.idx);
    let mut t = Table::new(&[
        "Unit",
        "idx",
        "Cost",
        "HP",
        "Atk",
        "Def",
        "Move",
        "Range",
        "Weapon",
        "XP",
        "Hidden",
        "Unlocked by",
        "Upgrades from",
        "Tribe",
        "Abilities",
    ]);
    for u in &list {
        let by = unlocked_by(d, &u.id, |t| &t.unit_unlocks);
        t.row(vec![
            code(&u.id),
            u.idx.to_string(),
            u.cost.to_string(),
            tenths(u.health),
            tenths(u.attack),
            tenths(u.defence),
            u.movement.to_string(),
            u.range.to_string(),
            weapon_name(u.weapon).unwrap_or("?").to_string(),
            u.promotion_limit.to_string(),
            if u.hidden { "yes".to_string() } else { "-".to_string() },
            codes(&by),
            u.upgrades_from.as_deref().map_or("-".to_string(), code),
            owners.get(&u.id).map_or("-".to_string(), |v| v.join(", ")),
            codes(&u.unit_abilities),
        ]);
    }
    o.push_str(&t.render());
    let mut water: Vec<&UnitData> = list.iter().copied().filter(|u| !u.movement_terrain.is_empty()).collect();
    water.sort_by_key(|u| u.idx);
    o.push_str("## Units bound to certain terrain\n\n");
    o.push_str(
        "A unit with a `movement_terrain` list may only enter those terrains, whatever the player's techs. \
         Training such a unit needs a neighbouring tile of one of them.\n\n",
    );
    let mut t = Table::new(&["Unit", "Terrain"]);
    for u in water {
        t.row(vec![code(&u.id), codes(&u.movement_terrain)]);
    }
    o.push_str(&t.render());
    o.push_str(
        "\nHow the stats are used: [combat](../combat.md), [movement](../movement.md), [abilities](../abilities.md).\n",
    );
    o
}

