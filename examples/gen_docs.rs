fn reward_parts(i: &ImprovementData) -> Vec<String> {
    i.rewards
        .iter()
        .map(|r| {
            let mut p = Vec::new();
            if let Some(n) = r.population {
                p.push(format!("pop {n:+}"));
            }
            if let Some(n) = r.currency {
                p.push(format!("stars {n:+}"));
            }
            if let Some(n) = r.score {
                p.push(format!("score {n:+}"));
            }
            p.join(" ")
        })
        .collect()
}

fn growth_parts(i: &ImprovementData) -> Vec<String> {
    i.growth_rewards
        .iter()
        .map(|g| {
            let mut p = Vec::new();
            if let Some(n) = g.population {
                p.push(format!("pop {n:+}"));
            }
            if let Some(n) = g.score {
                p.push(format!("score {n:+}"));
            }
            p.join(" ")
        })
        .collect()
}

fn or_dash(parts: Vec<String>) -> String {
    if parts.is_empty() {
        "-".to_string()
    } else {
        parts.join("; ")
    }
}

fn tagged(pairs: &[(&str, &Option<String>)]) -> Vec<String> {
    pairs.iter().filter_map(|(k, v)| v.as_ref().map(|v| format!("{k}:{v}"))).collect()
}

fn improvement_override_tribes(d: &GameLogicData, id: &str) -> String {
    let mut parts = Vec::new();
    for t in playable_tribes(d) {
        for (base, repl) in &t.improvement_overrides {
            if repl == id {
                parts.push(format!("{} ({base})", tribe_label(&t.id)));
            }
        }
    }
    if parts.is_empty() {
        "-".to_string()
    } else {
        parts.join(", ")
    }
}

fn improvements(d: &GameLogicData) -> String {
    let mut o = page(
        "Improvements and buildings",
        "Every improvement in the current rules: tile improvements, buildings that grow with their neighbours, \
         temples, monuments and the city itself. *Work* is the stars per level a level-based building pays \
         each turn. *Max level* 0 means the improvement has no levels. *Pop* is the population it adds to the \
         city that owns the tile, *score* the points it gives. Costs are in stars. *Hidden* improvements \
         cannot be built from the menu.",
    );
    let mut list: Vec<&ImprovementData> = d.improvements.values().collect();
    list.sort_by_key(|i| i.idx);

    o.push_str("## Cost and rewards\n\n");
    let mut t = Table::new(&[
        "Improvement",
        "idx",
        "Cost",
        "Work",
        "Border",
        "Max level",
        "Growth rate",
        "Rewards on building",
        "Rewards per level",
        "Abilities",
        "Hidden",
    ]);
    for i in &list {
        t.row(vec![
            code(&i.id),
            i.idx.to_string(),
            opt(i.cost),
            opt(i.work),
            opt(i.border_size),
            opt(i.max_level),
            opt(i.growth_rate),
            or_dash(reward_parts(i)),
            or_dash(growth_parts(i)),
            codes(&i.improvement_abilities),
            if i.hidden { "yes".to_string() } else { "-".to_string() },
        ]);
    }
    o.push_str(&t.render());

    o.push_str("\n## Placement and effects\n\n");
    o.push_str(
        "*Built on*: any one of the listed terrains or resources. *Needs next to it*: any one of the listed \
         neighbouring improvements or terrains. *Counts*: neighbours that raise its level. *Routes* are the \
         terrains a network improvement connects over, up to *range* tiles. *Creates* is what the tile becomes. \
         *Unlocked by* names the techs and tasks that make it buildable.\n\n",
    );
    let mut t = Table::new(&[
        "Improvement",
        "Built on",
        "Needs next to it",
        "Counts",
        "Routes (range)",
        "Creates",
        "Unlocked by",
        "Tribe",
    ]);
    for i in &list {
        let built: Vec<String> = i
            .terrain_requirements
            .iter()
            .flat_map(|r| tagged(&[("terrain", &r.terrain), ("resource", &r.resource)]))
            .collect();
        let next: Vec<String> = i
            .adjacency_requirements
            .iter()
            .flat_map(|r| {
                tagged(&[
                    ("terrain", &r.terrain),
                    ("improvement", &r.improvement),
                    ("resource", &r.resource),
                    ("not", &r.not_improvement),
                ])
            })
            .collect();
        let counts: Vec<String> = i
            .adjacency_improvements
            .iter()
            .flat_map(|r| tagged(&[("improvement", &r.improvement), ("resource", &r.resources)]))
            .collect();
        let creates: Vec<String> = i
            .creates
            .iter()
            .flat_map(|c| {
                tagged(&[("terrain", &c.terrain), ("resource", &c.resource), ("unit", &c.unit), ("effect", &c.effect)])
            })
            .collect();
        let mut by = unlocked_by(d, &i.id, |t| &t.improvement_unlocks);
        let tasks: Vec<String> = d
            .tasks
            .values()
            .filter(|t| t.improvement_unlocks.contains(&i.id))
            .map(|t| format!("task {}", t.id))
            .collect();
        by.extend(tasks);
        let routes =
            if i.routes.is_empty() { "-".to_string() } else { format!("{} ({})", codes(&i.routes), opt(i.range)) };
        t.row(vec![
            code(&i.id),
            codes(&built),
            codes(&next),
            codes(&counts),
            if i.routes.is_empty() && i.range.is_some() { format!("range {}", opt(i.range)) } else { routes },
            codes(&creates),
            codes(&by),
            improvement_override_tribes(d, &i.id),
        ]);
    }
    o.push_str(&t.render());
    o.push_str("How buildings, levels and income work: [cities and economy](../economy.md).\n");
    o
}

